import { readFile } from 'node:fs/promises';
import { test, expect } from './fixtures.ts';
import { finishMatch, startMatch } from './helpers.ts';
import { recordDetailSchema, recordDownloadSchema, recordsPageSchema } from '../src/protocol/records.ts';

test('완료한 대국의 목록·본선 복기·JSON 다운로드가 실제 착수를 보존한다', async ({ page, browser }) => {
  const { white, whiteContext } = await startMatch(page, browser);
  try {
    const final = await finishMatch(page, white);
    const response = await page.request.get(`/api/records/${final.code}`);
    expect(response.ok()).toBe(true);
    const detail = recordDetailSchema.parse(await response.json());
    expect(detail).toMatchObject({ boardSize: 19, moveCount: 19, historyStatus: 'native', clockAccuracy: 'exact', result: { status: 'finished', winner: 'black' } });
    expect(detail.finalState).toEqual(final.game);
    expect(detail.expiresAt - detail.endedAt).toBe(7 * 24 * 60 * 60 * 1000);
    await page.getByRole('link', { name: '기보 복기·브랜치 분석', exact: true }).click();
    await expect(page).toHaveURL(`/records/${final.code}`);
    await page.getByRole('button', { name: '처음', exact: true }).click();
    await expect(page.locator('[data-cell="0"]')).toHaveAttribute('aria-label', /빈 교차점/);
    const moves = page.getByRole('list', { name: '착수 목록', exact: true });
    await expect(moves.getByRole('listitem')).toHaveCount(19);
    await moves.getByRole('button').nth(1).click();
    await expect(moves.getByRole('button').nth(1)).toHaveAttribute('aria-current', 'step');
    await expect(page.locator('[data-cell="360"]')).toHaveAttribute('aria-label', /백 군사.*마지막 확정 착수/);
    await expect(page.locator('.last-move-marker')).toHaveCount(1);
    await expect(page.locator('.piece-glyph')).toHaveCount(0);
    await page.getByRole('button', { name: '처음', exact: true }).click();
    await expect(page.getByRole('button', { name: '이전 수', exact: true })).toBeDisabled();
    await page.getByRole('button', { name: '다음 수', exact: true }).click();
    await expect(page.locator('[data-cell="0"]')).toHaveAttribute('aria-label', /흑 군사.*마지막 확정 착수/);
    await expect(page.locator('[data-cell="360"]')).toHaveAttribute('aria-label', /빈 교차점/);
    await page.getByRole('button', { name: '다음 수', exact: true }).click();
    await expect(page.locator('[data-cell="360"]')).toHaveAttribute('aria-label', /백 군사/);
    await page.getByRole('button', { name: '이전 수', exact: true }).click();
    await expect(page.locator('[data-cell="360"]')).toHaveAttribute('aria-label', /빈 교차점/);
    await page.getByRole('button', { name: '마지막', exact: true }).click();
    await expect(page.locator('[data-cell="23"]')).toHaveAttribute('aria-label', /흑 군사.*보호됨/);
    await expect(page.getByRole('button', { name: '다음 수', exact: true })).toBeDisabled();
    const pendingDownload = page.waitForEvent('download');
    await page.getByRole('link', { name: 'JSON 기보 다운로드', exact: true }).click();
    const download = await pendingDownload;
    expect(await download.failure()).toBeNull();
    const path = await download.path();
    if (!path) throw new Error('Record download path missing');
    const exported = recordDownloadSchema.parse(JSON.parse(await readFile(path, 'utf8')));
    expect(exported.detail).toEqual(detail);
    expect(exported.moves).toHaveLength(19);
    expect(exported.moves.map(move => move.ply)).toEqual(Array.from({ length: 19 }, (_, index) => index + 1));
    expect(exported.moves[18]?.action).toEqual({ type: 'placeSoldier', at: 23 });
    expect(exported.analysis).toEqual([]);
    await page.goto('/records');
    await expect(page.getByRole('heading', { name: '내 기보', exact: true })).toBeVisible();
    const recordLink = page.locator(`a[href="/records/${final.code}"]`);
    await expect(recordLink).toContainText('19수');
    await expect(recordLink).toContainText('19 × 19');
    await recordLink.click();
    await page.reload();
    await expect(page.getByRole('button', { name: '처음', exact: true })).toBeVisible();
    const list = await white.request.get('/api/records');
    expect(list.ok()).toBe(true);
    expect(recordsPageSchema.parse(await list.json()).records.some(record => record.code === final.code)).toBe(true);
    await white.goto('/records');
    await expect(white.locator(`a[href="/records/${final.code}"]`)).toBeVisible();
  } finally { await whiteContext.close(); }
});
